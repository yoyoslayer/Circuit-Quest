import {launch} from '../cap.mjs';
import {grab} from './helpers.mjs';
const P='verify-arcade-models';
const g=await launch('arcade',{fullfx:true});
console.log('audit02@t0',JSON.stringify(await g.audit(.02)));
console.log('audit04@t0',JSON.stringify(await g.audit(.04)).length);
await grab(g);
const settle=async(n=20)=>{for(let i=0;i<n;i++)await g.advance(1/60);};
const shot=async(name)=>{await settle();return g.shot(`${P}-${name}`);};
const prompt=()=>g.page.evaluate(()=>[...document.querySelectorAll('body *')].filter(e=>e.children.length===0&&/Grab|Carry|Pick/.test(e.textContent)&&e.offsetParent).map(e=>e.textContent.trim()).join('|'));
const tilt=()=>g.page.evaluate(()=>{const T=window.__T,s=window.__circuitCrew.snapshot(),it=s.items.find(i=>i.id==='blocks');let best=null;
  window.__scene.traverse(o=>{if(!best&&o.isGroup&&o.children.length===6&&Math.hypot(o.position.x-it.pos.x,o.position.z-it.pos.z)<.01)best=o;});
  if(!best)return null;const up=new T.Vector3(0,1,0).applyQuaternion(best.quaternion);const p=s.player;return {upY:+up.y.toFixed(2),ty:+it.pos.y.toFixed(2),py:+p.y.toFixed(2),dist:+Math.hypot(it.pos.x-p.x,it.pos.z-p.z).toFixed(2)};});
const prompts=new Set();
const leg=async(x,z,r=.5)=>{const s=(await g.snap()).player;const n=Math.max(1,Math.ceil(Math.hypot(x-s.x,z-s.z)/.7));const out=[];for(let i=1;i<=n;i++){const tx=s.x+(x-s.x)*i/n,tz=s.z+(z-s.z)*i/n;await g.walk(tx,tz,i===n?r:.35);prompts.add(await prompt());const t=await tilt();if(t)out.push(t.upY);}return out;};
await g.advance(.3);
await leg(-5.5,6.6);await leg(-7.2,5.8);
console.log('prompts on way',[...prompts].join(' || '));
await leg(-8.3,4.4,.3);await g.key('KeyE');console.log('held',(await g.snap()).held,JSON.stringify(await tilt()));
const tilts=[];tilts.push(...await leg(-7.2,5.8));tilts.push(...await leg(-5.5,6.4));tilts.push(...await leg(-1,-.6));
console.log('tilt upY along route',tilts.join(','),'last',JSON.stringify(await tilt()));
await shot('10-carry-near-bench');
await g.crop(`${P}-10b-crop-carry`,{x:420,y:200,width:600,height:600});
console.log(await g.close());
